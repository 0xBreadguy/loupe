#!/usr/bin/env python3
"""Extract dashboard-relevant DDL from a pinned T3 source tree, in migration order.

This is NOT a T3 migrator: data transforms, preview reconciliation, FTS/search,
and unrelated tables are outside its scope. See schema-compatibility.md.
Usage: schema-extract.py CLONE COMMIT LIMIT OUTPUT
"""
import json, re, sqlite3, subprocess, sys
from pathlib import Path
repo, ref, limit, output = sys.argv[1:5]
limit = int(limit)
ref = subprocess.check_output(['git', '-C', repo, 'rev-parse', ref], text=True).strip()
base = 'apps/server/src/persistence/'
def read(path):
    return subprocess.check_output(['git', '-C', repo, 'show', f'{ref}:{path}'], text=True)
manifest = read(base + 'Migrations.ts')
entries = re.findall(r'import Migration\d+ from "\./Migrations/(\d+_\w+\.ts)"', manifest)
assert limit in {int(f[:3]) for f in entries}, 'migration limit not present at this commit'
tables = {'projection_projects', 'orchestration_events', 'orchestration_v2_events',
          'orchestration_v2_projection_metadata', 'orchestration_v2_effect_outbox',
          'orchestration_v2_effect_outbox_next', 'orchestration_v2_projection_turn_item_counts'}
tables |= {'orchestration_v2_projection_' + n for n in
           ['threads', 'runs', 'subagents', 'nodes', 'provider_threads', 'provider_turns', 'turn_items', 'runtime_requests']}
db = sqlite3.connect(':memory:')
trace = []
def extract(path):
    text = read(path)
    # Every selected DDL statement is a literal sql template; reject dynamic DDL.
    for sql in re.findall(r'\bsql(?:<[^`]*?>)?`([^`]+)`', text):
        if not re.match(r'\s*(CREATE|ALTER|DROP)\b', sql): continue
        targets = set(re.findall(r'\b(?:TABLE(?: IF (?:NOT )?EXISTS)?|ON)\s+([\w]+)', sql, re.I))
        if not targets & tables:
            drop = re.match(r'\s*DROP INDEX(?: IF EXISTS)? (\w+)', sql)
            if not drop or not db.execute("SELECT 1 FROM sqlite_master WHERE type='index' AND name=?", (drop[1],)).fetchone(): continue
        if '${' in sql: raise RuntimeError(f'dynamic DDL: {path}: {sql}')
        db.execute(sql)
        trace.append(f'-- {path}\n{sql.strip()};\n')
    if path.endswith('/055_OrchestrationV2.ts'):
        imports = dict(re.findall(r'import (\w+) from "(\./[^"]+)"', text))
        for name in re.findall(r'yield\* (\w+);', text.split('export default')[-1]):
            if name in imports: extract(str(Path(path).parent / imports[name]))
for filename in entries:
    if int(filename[:3]) <= limit: extract(base + 'Migrations/' + filename)
# The effect migrator owns this table; it is not declared in T3's migration files.
ledger = 'CREATE TABLE effect_sql_migrations (migration_id integer PRIMARY KEY NOT NULL, created_at datetime NOT NULL DEFAULT current_timestamp, name VARCHAR(255) NOT NULL);'
trace.append('-- Effect migrator ledger (same definition as existing fixture)\n' + ledger + '\n')
for filename in entries:
    if int(filename[:3]) <= limit:
        trace.append(f"INSERT INTO effect_sql_migrations(migration_id,name) VALUES ({int(filename[:3])},'{filename[4:-3]}');\n")
header = f'-- T3 commit {ref}; migrations 001..{limit:03d}.\n-- Dashboard-relevant DDL replay, not a full T3 database or data migration replay.\n-- Generated by checks/scripts/schema-extract.py.\n'
Path(output).write_text(header + '\n'.join(trace))
print(json.dumps({'commit':ref,'limit':limit,'tables':len(list(db.execute("SELECT name FROM sqlite_master WHERE type='table'"))),'output':output}))

# Optional exact SQL for the canonical 083 -> 096 dashboard-table upgrade.
# 087's column guard takes its absent-column branch on canonical 083.
if len(sys.argv) == 6:
    assert limit == 96
    stages = []
    for filename in entries:
        number = int(filename[:3])
        if number < 84: continue
        path = base + 'Migrations/' + filename
        statements = []
        for sql in re.findall(r'\bsql(?:<[^`]*?>)?`([^`]+)`', read(path)):
            if re.match(r'\s*PRAGMA', sql): continue
            if number in (90, 91): continue  # auth only, outside dashboard schema
            assert '${' not in sql, path
            statements.append(sql.strip())
        stages.append({'id':number,'name':filename[4:-3],'source':path,'sql':statements})
    Path(sys.argv[5]).write_text(json.dumps({'commit':ref,'from':83,'to':96,'stages':stages},indent=2)+'\n')
